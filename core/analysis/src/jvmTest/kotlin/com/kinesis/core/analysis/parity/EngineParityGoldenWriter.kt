package com.kinesis.core.analysis.parity

import java.io.File
import kotlin.test.Test

/**
 * Writes `EngineParityGolden.kt` from a JVM run - DECISIONS.md P3-19.
 *
 * Does nothing unless asked, so an ordinary run can never quietly re-baseline
 * the parity suite. To regenerate, deliberately, after an engine change that is
 * meant to move the output:
 *
 *     KINESIS_WRITE_GOLDEN=1 gradlew :core:analysis:jvmTest --tests "*EngineParityGoldenWriter*"
 *
 * then review the diff of the golden file like any other change.
 */
class EngineParityGoldenWriter {

    @Test
    fun write_the_golden_file_when_asked() {
        if (System.getenv("KINESIS_WRITE_GOLDEN") != "1") return
        val target = File("src/commonTest/kotlin/com/kinesis/core/analysis/parity/EngineParityGolden.kt")
        check(target.parentFile.isDirectory) { "run from core/analysis; no ${target.parentFile}" }
        val out = StringBuilder()
        out.append("package com.kinesis.core.analysis.parity\n\n")
        out.append("// GENERATED by EngineParityGoldenWriter on the JVM - DECISIONS.md P3-19.\n")
        out.append("// Do not edit by hand. Regenerate deliberately and review the diff.\n\n")
        out.append("internal object EngineParityGolden {\n")
        val scenarios = listOf(
            "squat" to EngineParity.squat(),
            "plank" to EngineParity.plank(),
            // DECISIONS.md P3-22.
            "squatCalibration" to EngineParity.squatCalibration(),
            "curlCalibration" to EngineParity.curlCalibration(),
            "plankCalibration" to EngineParity.plankCalibration(),
            // DECISIONS.md P3-25.
            "sessionExport" to EngineParity.sessionExport(),
        )
        for ((name, lines) in scenarios) {
            out.append("\n    val ").append(name).append(": List<String> = listOf(\n")
            for (line in lines) out.append("        \"").append(escape(line)).append("\",\n")
            out.append("    )\n")
        }
        out.append("}\n")
        target.writeText(out.toString())
        println("wrote ${target.absolutePath}")
    }

    private fun escape(line: String): String =
        line.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\$")
}
