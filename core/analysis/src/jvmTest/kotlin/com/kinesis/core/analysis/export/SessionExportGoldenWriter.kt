package com.kinesis.core.analysis.export

import java.io.File
import kotlin.test.Test

/**
 * Writes `SessionExportGolden.kt` from a JVM run - DECISIONS.md P3-25.
 *
 * Does nothing unless asked, so an ordinary run can never quietly re-baseline
 * the export's golden file. To regenerate, deliberately, after a change that is
 * meant to move the format - and with [SessionExport.FORMAT_VERSION] raised if a
 * field was added, removed, renamed or changed meaning:
 *
 *     KINESIS_WRITE_GOLDEN=1 gradlew :core:analysis:jvmTest --tests "*SessionExportGoldenWriter*" --rerun
 *
 * then review the diff of the golden file like any other change.
 */
class SessionExportGoldenWriter {

    @Test
    fun write_the_golden_file_when_asked() {
        if (System.getenv("KINESIS_WRITE_GOLDEN") != "1") return
        val target = File("src/commonTest/kotlin/com/kinesis/core/analysis/export/SessionExportGolden.kt")
        check(target.parentFile.isDirectory) { "run from core/analysis; no ${target.parentFile}" }
        val fixture = SessionExportFixture
        val csv = SessionExport.csv(fixture.sessions)
        val out = StringBuilder()
        out.append("package com.kinesis.core.analysis.export\n\n")
        out.append("// GENERATED by SessionExportGoldenWriter on the JVM - DECISIONS.md P3-25.\n")
        out.append("// Do not edit by hand. Regenerate deliberately and review the diff.\n\n")
        out.append("internal object SessionExportGolden {\n")
        for ((name, text) in listOf(
            "json" to SessionExport.json(fixture.sessions, fixture.baselines, fixture.EXPORTED_AT),
            "setsCsv" to csv.sets,
            "repsCsv" to csv.reps,
            "holdsCsv" to csv.holds,
        )) {
            out.append("\n    val ").append(name).append(": String =\n")
            // One Kotlin string literal per line of the file, so the diff reads by line.
            val lines = text.split("\r\n")
            for ((i, line) in lines.withIndex()) {
                val last = i == lines.lastIndex
                if (last && line.isEmpty()) continue
                val ending = if (last) "" else "\\r\\n"
                val joiner = if (i < lines.lastIndex - (if (lines.last().isEmpty()) 1 else 0)) " +" else ""
                out.append("        \"").append(escape(line)).append(ending).append("\"").append(joiner).append("\n")
            }
        }
        out.append("}\n")
        target.writeText(out.toString())
        println("wrote ${target.absolutePath}")
    }

    private fun escape(line: String): String =
        line.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")
}
