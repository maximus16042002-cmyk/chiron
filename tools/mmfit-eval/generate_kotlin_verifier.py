"""Generates Kotlin source code for PretrainedExerciseVerifierModel and VerifierParityGolden.
"""
import json
import os

def format_doubles(arr, indent=8, per_line=4):
    lines = []
    curr = []
    pad = " " * indent
    for val in arr:
        s = f"{float(val):.17g}"
        if "." not in s and "e" not in s.lower():
            s += ".0"
        curr.append(s)
        if len(curr) >= per_line:
            lines.append(pad + ", ".join(curr) + ",")
            curr = []
    if curr:
        lines.append(pad + ", ".join(curr) + ",")
    return "\n".join(lines)

def main():
    root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
    model_json_path = os.path.join(root, "data", "verifier", "exercise_verifier_model.json")
    parity_json_path = os.path.join(root, "data", "verifier", "verifier_parity_vectors.json")

    with open(model_json_path) as f:
        model = json.load(f)

    with open(parity_json_path) as f:
        parity_vectors = json.load(f)

    # 1. Generate PretrainedExerciseVerifierModel.kt
    kt_model_path = os.path.join(
        root,
        "core", "analysis", "src", "commonMain", "kotlin",
        "com", "kinesis", "core", "analysis", "verifier",
        "PretrainedExerciseVerifierModel.kt"
    )

    classes_str = ", ".join(f'"{c}"' for c in model["classes"])
    feature_names_str = ", ".join(f'"{f}"' for f in model["featureNames"])

    weights_blocks = []
    for cls_idx, w_row in enumerate(model["weights"]):
        cls_name = model["classes"][cls_idx]
        w_block = f"        // Class {cls_idx}: {cls_name}\n        doubleArrayOf(\n"
        w_block += format_doubles(w_row, indent=12, per_line=4)
        w_block += "\n        ),"
        weights_blocks.append(w_block)
    weights_str = "\n".join(weights_blocks)

    model_kt_content = f"""package com.kinesis.core.analysis.verifier

/**
 * Pre-trained multinomial logistic regression weights for the exercise verifier (P3-52).
 *
 * Generated automatically from MM-Fit development training by tools/mmfit-eval/generate_kotlin_verifier.py.
 * Do not edit by hand.
 */
object PretrainedExerciseVerifierModel {{

    const val MODEL_VERSION: String = "{model['modelVersion']}"

    val CLASSES: List<String> = listOf({classes_str})

    val FEATURE_NAMES: List<String> = listOf({feature_names_str})

    val SCALER_MEAN: DoubleArray = doubleArrayOf(
{format_doubles(model['scalerMean'], indent=8, per_line=4)}
    )

    val SCALER_SCALE: DoubleArray = doubleArrayOf(
{format_doubles(model['scalerScale'], indent=8, per_line=4)}
    )

    val INTERCEPTS: DoubleArray = doubleArrayOf(
{format_doubles(model['intercepts'], indent=8, per_line=4)}
    )

    val WEIGHTS: Array<DoubleArray> = arrayOf(
{weights_str}
    )

    val INSTANCE: ExerciseVerifierModel by lazy {{
        ExerciseVerifierModel(
            modelVersion = MODEL_VERSION,
            classes = CLASSES,
            featureNames = FEATURE_NAMES,
            scalerMean = SCALER_MEAN,
            scalerScale = SCALER_SCALE,
            intercepts = INTERCEPTS,
            weights = WEIGHTS,
            selectedPMax = {model['mismatchThresholds']['selectedPMax']},
            predictedPMin = {model['mismatchThresholds']['predictedPMin']},
        )
    }}
}}
"""

    os.makedirs(os.path.dirname(kt_model_path), exist_ok=True)
    with open(kt_model_path, "w", encoding="utf-8") as f:
        f.write(model_kt_content)
    print(f"Generated {kt_model_path}")

    # 2. Generate VerifierParityGolden.kt (use 20 representative vectors for test speed and size)
    kt_parity_path = os.path.join(
        root,
        "core", "analysis", "src", "commonTest", "kotlin",
        "com", "kinesis", "core", "analysis", "verifier",
        "VerifierParityGolden.kt"
    )

    selected_vectors = parity_vectors[:25] # 25 test vectors covering all 10 classes
    vector_blocks = []
    for v in selected_vectors:
        v_block = f"""        Vector(
            sampleIndex = {v['sampleIndex']},
            subject = "{v['subject']}",
            workout = "{v['workout']}",
            trueExercise = "{v['trueExercise']}",
            expectedPrediction = "{v['expectedPrediction']}",
            rawFeatures = doubleArrayOf(
{format_doubles(v['rawFeatures'], indent=16, per_line=4)}
            ),
            expectedProbabilities = doubleArrayOf(
{format_doubles(v['expectedProbabilities'], indent=16, per_line=4)}
            ),
        ),"""
        vector_blocks.append(v_block)

    parity_kt_content = f"""package com.kinesis.core.analysis.verifier

// GENERATED by tools/mmfit-eval/generate_kotlin_verifier.py - DECISIONS.md P3-52.
// Do not edit by hand.

internal object VerifierParityGolden {{

    class Vector(
        val sampleIndex: Int,
        val subject: String,
        val workout: String,
        val trueExercise: String,
        val expectedPrediction: String,
        val rawFeatures: DoubleArray,
        val expectedProbabilities: DoubleArray,
    )

    val VECTORS: List<Vector> = listOf(
{chr(10).join(vector_blocks)}
    )
}}
"""

    os.makedirs(os.path.dirname(kt_parity_path), exist_ok=True)
    with open(kt_parity_path, "w", encoding="utf-8") as f:
        f.write(parity_kt_content)
    print(f"Generated {kt_parity_path}")

if __name__ == "__main__":
    main()
